class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and print total page count 'Page X of Y'
    along with running header and footer lines.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor('#64748B'))

        # Running Footer
        footer_y = 25
        page_w, page_h = self._pagesize

        # Footer divider line
        self.setStrokeColor(colors.HexColor('#E2E8F0'))
        self.setLineWidth(0.75)
        self.line(36, footer_y + 12, page_w - 36, footer_y + 12)

        # Left footer: System & Confidentiality
        self.drawString(36, footer_y, "CONFIDENTIAL — Generated by Payroll MGM System")

        # Right footer: Page number
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(page_w - 36, footer_y, page_str)

        # Center footer: Timestamp
        now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        self.drawCentredString(page_w / 2.0, footer_y, f"Generated on {now_str}")

        self.restoreState()


