def build_signature_block(page_width=500):
    """Generates standard executive authorization sign-off block."""
    styles = get_pdf_styles()
    sig_data = [
        [
            Paragraph("<b>Prepared By:</b>", styles['TableCellBold']),
            Paragraph("<b>Verified By HR:</b>", styles['TableCellBold']),
            Paragraph("<b>Approved By Management:</b>", styles['TableCellBold'])
        ],
        [
            Paragraph("<br/><br/>_______________________<br/>Signature & Date", styles['TableCell']),
            Paragraph("<br/><br/>_______________________<br/>Signature & Date", styles['TableCell']),
            Paragraph("<br/><br/>_______________________<br/>Signature & Date", styles['TableCell'])
        ]
    ]
    col_w = page_width / 3.0
    t = Table(sig_data, colWidths=[col_w, col_w, col_w])
    t.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
    ]))
    return KeepTogether([Spacer(1, 20), t])


